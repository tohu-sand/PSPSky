#!/bin/sh
# Generates assets/cacert.pem: only the roots needed to verify bsky.social,
# because the full bundle (~180KB) wastes PSP memory and load time. The result
# is committed, since the PSP has no way to fetch it.
#
# Usage:  sh tools/make_cacert.sh
set -eu

REPO_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
OUT="$REPO_ROOT/assets/cacert.pem"
SRC_URL="https://curl.se/ca/cacert.pem"
SYSTEM_BUNDLE="/etc/ssl/certs/ca-certificates.crt"

# Roots to extract, one per line, matched exactly: the Amazon Trust chain
# bsky.social uses today, its Starfield cross-signer, and ISRG X1 as a hedge.
WANTED='Amazon Root CA 1
Amazon Root CA 2
Amazon Root CA 3
Amazon Root CA 4
Starfield Services Root Certificate Authority - G2
ISRG Root X1'

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT INT TERM

# --- fetch the input bundle ----------------------------------------------
BUNDLE="$WORK/bundle.pem"
MODE=""
if command -v curl >/dev/null 2>&1 &&
   curl -fsSL --retry 3 --connect-timeout 20 -o "$BUNDLE" "$SRC_URL"; then
    MODE="upstream"
    echo "source: $SRC_URL"
elif [ -r "$SYSTEM_BUNDLE" ]; then
    cp "$SYSTEM_BUNDLE" "$BUNDLE"
    MODE="system"
    echo "source: $SYSTEM_BUNDLE (fallback: upstream fetch failed)"
else
    echo "error: could not fetch $SRC_URL and $SYSTEM_BUNDLE is not readable" >&2
    exit 1
fi

command -v openssl >/dev/null 2>&1 || { echo "error: openssl not found" >&2; exit 1; }

# --- extraction helpers --------------------------------------------------

# The curl bundle labels each certificate, so cut from the label to END.
extract_by_label() {
    awk -v want="$1" '
        $0 == want            { hit = 1; next }
        hit && /^-----BEGIN CERTIFICATE-----$/ { inc = 1 }
        inc                   { print }
        inc && /^-----END CERTIFICATE-----$/   { exit }
    ' "$2"
}

# The system bundle has no labels, so split it and match on subject CN.
split_bundle() {
    awk -v dir="$1" '
        /^-----BEGIN CERTIFICATE-----$/ { n++; f = sprintf("%s/cert-%04d.pem", dir, n) }
        f != ""                         { print > f }
        /^-----END CERTIFICATE-----$/   { if (f != "") { close(f); f = "" } }
    ' "$2"
}

extract_by_cn() {
    want="$1"
    for c in "$2"/cert-*.pem; do
        [ -e "$c" ] || continue
        cn=$(openssl x509 -noout -subject -nameopt multiline -in "$c" 2>/dev/null |
             sed -n 's/^[[:space:]]*commonName[[:space:]]*=[[:space:]]*//p' | head -n 1)
        if [ "$cn" = "$want" ]; then
            cat "$c"
            return 0
        fi
    done
    return 1
}

if [ "$MODE" = "system" ]; then
    SPLIT="$WORK/split"
    mkdir -p "$SPLIT"
    split_bundle "$SPLIT" "$BUNDLE"
fi

# --- generate -------------------------------------------------------------
TMP_OUT="$WORK/cacert.pem"
{
    echo "# PSPSky minimal CA bundle"
    echo "# Generated by tools/make_cacert.sh — do not edit by hand."
    echo "# Regenerate with:  sh tools/make_cacert.sh"
    echo "#"
    echo "# Roots required to verify https://bsky.social from the PSP."
    echo "# Deploy alongside EBOOT.PBP as ms0:/PSP/GAME/PSPSKY/cacert.pem"
    echo ""
} > "$TMP_OUT"

missing=0
echo "$WANTED" | while IFS= read -r name; do
    [ -n "$name" ] || continue
    if [ "$MODE" = "upstream" ]; then
        pem=$(extract_by_label "$name" "$BUNDLE" || true)
    else
        pem=$(extract_by_cn "$name" "$SPLIT" || true)
    fi
    if [ -z "$pem" ]; then
        echo "error: certificate not found in source bundle: $name" >&2
        exit 1
    fi
    {
        echo "$name"
        echo "$name" | sed 's/./=/g'
        echo "$pem"
        echo ""
    } >> "$TMP_OUT"
    echo "  + $name"
done || missing=1
[ "$missing" -eq 0 ] || exit 1

# --- verify ---------------------------------------------------------------
want_count=$(echo "$WANTED" | grep -c .)
got_count=$(grep -c '^-----BEGIN CERTIFICATE-----$' "$TMP_OUT" || true)
if [ "$got_count" -ne "$want_count" ]; then
    echo "error: expected $want_count certificates, got $got_count" >&2
    exit 1
fi

VERIFY="$WORK/verify"
mkdir -p "$VERIFY"
split_bundle "$VERIFY" "$TMP_OUT"
for c in "$VERIFY"/cert-*.pem; do
    openssl x509 -noout -subject -in "$c" >/dev/null 2>&1 || {
        echo "error: openssl could not parse $c" >&2
        exit 1
    }
done

mkdir -p "$(dirname "$OUT")"
cp "$TMP_OUT" "$OUT"
echo "wrote $OUT ($got_count certificates, $(wc -c < "$OUT") bytes)"
